// Builds supabase/migrations/0002_setup_wedding.sql from src/lib/seedData.ts, so the app and the database
// start from the same data. Regenerate with `npm run gen:seed`; supabase/tests/seed.test.ts fails if they drift.
import {
  DEFAULT_FX, DEFAULT_GUESTS, DEFAULT_TOTAL_USD, DEFAULT_WEDDING_DATE,
  SEED_CATEGORIES, SEED_EVENTS, SEED_NOTES, TASK_TEMPLATE,
} from '../../src/lib/seedData';

export const SEED_SQL_PATH = 'supabase/migrations/0002_setup_wedding.sql';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const b = (v: boolean | undefined) => (v ? 'true' : 'false');
const rows = (lines: string[]) => lines.map((l, i) => `      ${l}${i < lines.length - 1 ? ',' : ''}`).join('\n');

export function buildSeedSql(): string {
  const events = rows(SEED_EVENTS.map((e, i) => `(${q(e.key)}, ${q(e.name)}, ${b(e.is_on)}, ${b(e.is_fixed)}, ${i})`));
  const cats = rows(SEED_CATEGORIES.map(([key, name, amount, locked, ev], i) =>
    `(${q(key)}, ${q(name)}, ${amount}, ${b(locked)}, ${q(ev)}, ${i})`));
  const tasks = rows(TASK_TEMPLATE.map(([m, title, area, who, done], i) =>
    `(${m}, ${q(title)}, ${q(area)}, ${q(who)}, ${b(done)}, ${i})`));
  const notes = rows(SEED_NOTES.map(([type, body], i) => `(${q(type)}, ${q(body)}, ${i})`));

  return `-- GENERATED by \`npm run gen:seed\` from src/lib/seedData.ts. Don't edit by hand.
--
-- setup_wedding(): the first-run "Set up our wedding" step. The signed-in user becomes the first owner, and the
-- wedding starts with the events, budget categories, checklist and decision notes from the prototype.
-- This app holds a single wedding, so it refuses once one exists. Everyone else joins by invitation.

create or replace function public.setup_wedding(
  p_display_name text default null,
  p_wedding_date date default ${q(DEFAULT_WEDDING_DATE)}
) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_email text;
  v_wedding uuid;
begin
  if v_uid is null then
    raise exception 'Sign in before setting up the wedding.' using errcode = 'insufficient_privilege';
  end if;
  perform pg_advisory_xact_lock(hashtext('public.setup_wedding'));
  if exists (select 1 from public.weddings) then
    raise exception 'The wedding is already set up. Ask Nick or Thuraya to invite you.' using errcode = 'unique_violation';
  end if;

  select u.email into v_email from auth.users u where u.id = v_uid;

  insert into public.weddings (couple_names, wedding_date, date_confirmed, guest_target, total_budget_usd, fx_cop_per_usd)
  values ('Nick & Thuraya', p_wedding_date, false, ${DEFAULT_GUESTS}, ${DEFAULT_TOTAL_USD}, ${DEFAULT_FX})
  returning id into v_wedding;

  insert into public.members (wedding_id, user_id, email, display_name, role)
  values (v_wedding, v_uid, coalesce(v_email, ''),
          coalesce(nullif(trim(p_display_name), ''), split_part(coalesce(v_email, 'Owner'), '@', 1)), 'owner');

  insert into public.events (wedding_id, key, name, is_on, is_fixed, sort)
  select v_wedding, e.key, e.name, e.is_on, e.is_fixed, e.sort
  from (values
${events}
  ) as e (key, name, is_on, is_fixed, sort);

  insert into public.budget_categories (wedding_id, event_id, key, name, amount_usd, is_locked, is_buffer, sort)
  select v_wedding, ev.id, c.key, c.name, c.amount, c.locked, c.key = 'buffer', c.sort
  from (values
${cats}
  ) as c (key, name, amount, locked, event_key, sort)
  join public.events ev on ev.wedding_id = v_wedding and ev.key = c.event_key;

  -- Due = wedding date − whole months (clamped to month end), then the fraction as ~30-day steps.
  insert into public.tasks (wedding_id, title, area, assignee, due_date, is_done, months_before, sort)
  select v_wedding, t.title, t.area, t.assignee,
         (p_wedding_date - make_interval(months => floor(t.m)::int))::date - round((t.m - floor(t.m)) * 30)::int,
         t.done, t.m, t.sort
  from (values
${tasks}
  ) as t (m, title, area, assignee, done, sort);

  insert into public.notes (wedding_id, type, body, created_at)
  select v_wedding, n.type, n.body, now() + make_interval(secs => n.sort)
  from (values
${notes}
  ) as n (type, body, sort);

  return v_wedding;
end $$;

revoke execute on function public.setup_wedding(text, date) from public, anon;
grant execute on function public.setup_wedding(text, date) to authenticated;
`;
}
